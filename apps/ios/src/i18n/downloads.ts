/** The English reasons downloads.ts keeps with a failed download, said here in the language. */
const KEPT = [
  "This download stopped.",
  "The download couldn't go on from where it stopped.",
  "The file arrived incomplete.",
  "This download's record is damaged, so it can't be removed safely yet.",
  "This download's last result isn't written down yet.",
  "Stop playing this copy first.",
  "The old copy is still closing. Try again.",
  "The pause couldn't be kept.",
  "The download couldn't be resumed.",
  "The new order couldn't be kept.",
] as const satisfies readonly Parameters<typeof t>[0][];

/** `detail` in the interface language when it is one of downloads.ts's own; else as it came. */
function said(detail: string): string {
  const kept = KEPT.find((each) => each === detail);
  return kept ? t(kept) : detail;
}

/**
 * `error` with downloads.ts's English reason in the interface language, for errors.ts's
 * `describeError`. The stored record keeps its English, which every version reads.
 */
export function inLanguage(error: AppError): AppError {
  if (error.kind === "unexpected") return { ...error, detail: said(error.detail) };
  if (error.kind === "stream" && "detail" in error.failure) {
    return { ...error, failure: { ...error.failure, detail: said(error.failure.detail) } };
  }
  return error;
}
